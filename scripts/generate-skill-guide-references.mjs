import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const targets = ['stdf', 'rtdf', 'vtdf'];
const guides = ['quickStart', 'compatibility', 'theme', 'icon', 'iconPlugin', 'internation', 'create', 'feedback', 'utils', 'mdPlugin'];
const routes = { 'quick-start': 'quickStart', 'icon-plugin': 'iconPlugin', md: 'mdPlugin', internationalization: 'internation' };

export const renderGuide = (source, target, name, availableGuides) => {
	const body = source
		.replace(/^\[[^\]]*\p{Script=Han}[^\]]*\]\([^)]*\)\s*/u, '')
		.replace(/\]\(\/guide\)/g, '](./quickStart.md)')
		.replace(/\]\((?:https:\/\/(?:stdf|rtdf|vtdf)\.dev)?\/guide\/([^)?#]+)(?:\?[^)#]*)?(#[^)]*)?\)/g, (_, route, anchor = '') => {
			const guide = routes[route] ?? route;
			if (availableGuides.includes(guide)) return `](./${guide}.md${anchor})`;
			if (route === 'color') return `](../color.md${anchor})`;
			return `](https://${target}.dev/guide/${route}${anchor})`;
		})
		.replace(/\]\((?:https:\/\/(?:stdf|rtdf|vtdf)\.dev)?\/components\?nav=([A-Za-z0-9]+)(?:&|&amp;)tab=\d+\)/g, (_, nav) => `](../components/${nav}.md)`);
	return `<!-- generated by scripts/generate-skill-guide-references.mjs; do not edit -->\n<!-- source-docs: content/${target}/guide/${name}_en.md -->\n\n${body.trim()}\n`;
};

const generateTarget = (target, check) => {
	const names = target === 'stdf' ? [...guides, 'upgrade'] : guides;
	const references = path.join(repositoryRoot, 'packages/skills', `${target}-skill`, target, 'references');
	const actualDirectory = path.join(references, 'guides');
	const temporaryRoot = mkdtempSync(path.join(os.tmpdir(), `${target}-skill-guides-`));
	try {
		const version = JSON.parse(readFileSync(path.join(repositoryRoot, 'packages', target, 'package.json'), 'utf-8')).version;
		const index = [
			`# ${target.toUpperCase()} Guide Reference`,
			'',
			'<!-- generated by scripts/generate-skill-guide-references.mjs; do not edit -->',
			`<!-- library-version: ${version} -->`,
			'',
			'These offline guides reflect the repository documentation for the library version above. This is a documentation snapshot, not an installed application dependency or a Skill release version. Read only the guide needed for the task. For an older installed library, verify its contract before applying current guidance.',
			'',
			...names.map((name) => `- [${name}](guides/${name}.md)`),
			''
		].join('\n');
		writeFileSync(path.join(temporaryRoot, 'guides.md'), index);
		mkdirSync(path.join(temporaryRoot, 'guides'));
		for (const name of names) {
			const source = readFileSync(path.join(repositoryRoot, 'content', target, 'guide', `${name}_en.md`), 'utf-8');
			writeFileSync(path.join(temporaryRoot, 'guides', `${name}.md`), renderGuide(source, target, name, names));
		}
		const outputs = ['guides.md', ...names.map((name) => `guides/${name}.md`)];
		const formatter = path.join(repositoryRoot, 'node_modules/.bin', process.platform === 'win32' ? 'vp.cmd' : 'vp');
		execFileSync(formatter, ['fmt', ...outputs.map((file) => path.join(temporaryRoot, file))], { cwd: repositoryRoot, stdio: 'inherit' });
		if (check) {
			const actualNames = existsSync(actualDirectory) ? readdirSync(actualDirectory).sort() : [];
			if (actualNames.join('\n') !== names.map((name) => `${name}.md`).sort().join('\n')) {
				throw new Error(`${target} skill guide file list is out of date. Run bun run generate:skills.`);
			}
			for (const file of outputs) {
				const actual = path.join(references, file);
				if (!existsSync(actual) || readFileSync(actual, 'utf-8') !== readFileSync(path.join(temporaryRoot, file), 'utf-8')) {
					throw new Error(`${target} skill ${file} is out of date. Run bun run generate:skills.`);
				}
			}
		} else {
			rmSync(actualDirectory, { recursive: true, force: true });
			mkdirSync(actualDirectory, { recursive: true });
			for (const file of outputs) writeFileSync(path.join(references, file), readFileSync(path.join(temporaryRoot, file)));
		}
		console.log(`${target} skill guides ${check ? 'are up to date' : 'generated'} (${names.length} guides).`);
	} finally {
		rmSync(temporaryRoot, { recursive: true, force: true });
	}
};

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
	const args = process.argv.slice(2);
	const targetIndex = args.indexOf('--target');
	const target = args[targetIndex + 1];
	if (targetIndex === -1 || ![...targets, 'all'].includes(target)) throw new Error('--target must be stdf, rtdf, vtdf, or all.');
	const remaining = args.filter((_, index) => index !== targetIndex && index !== targetIndex + 1);
	if (remaining.some((arg) => arg !== '--check')) throw new Error(`Unknown arguments: ${remaining.join(' ')}`);
	for (const name of target === 'all' ? targets : [target]) generateTarget(name, remaining.includes('--check'));
}
