const outputs = new Map();
for (const framework of frameworks) {
	outputs.set(`content/${framework.id}/guide/vscode.md`, renderGuide(framework, 'zh'));
	outputs.set(`content/${framework.id}/guide/vscode_en.md`, renderGuide(framework, 'en'));
}
outputs.set('extensions/vscode-extension/README.md', renderEnglishReadme());
outputs.set('extensions/vscode-extension/README_CN.md', renderChineseReadme());

const stalePaths = [];
let updatedCount = 0;

for (const [repositoryPath, expectedContent] of outputs) {
	const outputPath = resolve(repositoryRoot, repositoryPath);
	const actualContent = existsSync(outputPath) ? readFileSync(outputPath, 'utf8') : '';
	if (actualContent === expectedContent) continue;

	if (checkOnly) {
		stalePaths.push(repositoryPath);
		continue;
	}

	mkdirSync(dirname(outputPath), { recursive: true });
	writeFileSync(outputPath, expectedContent, 'utf8');
	updatedCount += 1;
}

if (checkOnly && stalePaths.length > 0) {
	for (const repositoryPath of stalePaths) console.error(`Generated VS Code documentation is stale: ${repositoryPath}`);
	process.exit(1);
}

if (checkOnly) {
	console.log(`PASS generated VS Code documentation (${outputs.size} files)`);
} else if (updatedCount === 0) {
	console.log(`No generated VS Code documentation changes (${outputs.size} files)`);
} else {
	console.log(`Updated generated VS Code documentation (${updatedCount}/${outputs.size} files)`);
}
