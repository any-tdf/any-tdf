import { execFileSync } from 'node:child_process';
import { copyFileSync, existsSync, mkdirSync, mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const repositoryRoot = path.resolve(scriptDir, '..');

const configs = {
	stdf: {
		brand: 'STDF',
		packageName: 'stdf',
		skillPackage: 'stdf-skill'
	},
	rtdf: {
		brand: 'RTDF',
		packageName: 'rtdf',
		skillPackage: 'rtdf-skill'
	},
	vtdf: {
		brand: 'VTDF',
		packageName: 'vtdf',
		skillPackage: 'vtdf-skill'
	}
};

const parseArgs = () => {
	const args = process.argv.slice(2);
	const options = { check: false, target: null };

	for (let index = 0; index < args.length; index += 1) {
		const arg = args[index];
		if (arg === '--check') {
			options.check = true;
		} else if (arg === '--target') {
			options.target = args[index + 1];
			index += 1;
		} else {
			throw new Error(`Unknown argument: ${arg}`);
		}
	}

	if (!options.target || (!configs[options.target] && options.target !== 'all')) {
		throw new Error('--target must be stdf, rtdf, vtdf, or all.');
	}

	return options;
};

const readMenuList = () => {
	const sourcePath = path.join(repositoryRoot, 'apps/site-common/src/stdf-data/menuList.ts');
	const source = readFileSync(sourcePath, 'utf-8');
	const marker = 'export const menuList: MenuList[] = ';
	const start = source.indexOf(marker);
	const arrayStart = source.indexOf('[', start);
	const arrayEnd = source.indexOf('\n];', arrayStart) + 2;

	if (start === -1 || arrayStart === -1 || arrayEnd === 1) {
		throw new Error(`Unable to parse component menu: ${sourcePath}`);
	}

	return new Function(`return ${source.slice(arrayStart, arrayEnd)};`)();
};

const normalizeEnglishDoc = (content) =>
	content
		.replace(
			'[德育处主任](https://gitee.com/k21vin/front-end-data-visualization/tree/master/src/views/Native/PureCSS/pages/Loading/components)',
			'[front-end-data-visualization](https://gitee.com/k21vin/front-end-data-visualization/tree/master/src/views/Native/PureCSS/pages/Loading/components)'
		)
		.replace(
			/\]\((?:https:\/\/(?:stdf|rtdf|vtdf)\.dev)?\/components\?nav=([A-Za-z0-9]+)(?:&|&amp;)tab=\d+\)/g,
			(_, nav) => `](./${nav}.md)`
		);

const listDocs = (target, componentName) => {
	const docsDir = path.join(repositoryRoot, 'content', target, 'components', componentName);
	const preferred = ['guide_en.md', 'api_en.md', 'FAQ_en.md', 'version_en.md'];

	return preferred
		.filter((fileName) => existsSync(path.join(docsDir, fileName)))
		.map((fileName) => ({
			absolutePath: path.join(docsDir, fileName),
			repositoryPath: `content/${target}/components/${componentName}/${fileName}`
		}));
};

const sectionTitles = {
	api: 'API',
	FAQ: 'FAQ',
	guide: 'Guide',
	version: 'Version'
};

const formatDocTitle = (filePath) => {
	const name = path.basename(filePath).replace('_en.md', '').replace('.md', '');
	return sectionTitles[name] ?? name;
};

const renderComponentDetail = ({ config, row }) => {
	const sourcePaths = row.docs.map((doc) => doc.repositoryPath).join(', ');
	const sections = row.docs
		.map((doc) => {
			const content = normalizeEnglishDoc(readFileSync(doc.absolutePath, 'utf-8').trim());
			return `## ${formatDocTitle(doc.absolutePath)}\n\n${content}`;
		})
		.join('\n\n');

	return `# ${row.component}

<!-- generated by scripts/generate-skill-component-references.mjs; do not edit -->
<!-- source-docs: ${sourcePaths || 'none'} -->

- Category: ${row.category}
- Route nav: \`${row.nav}\`

## Offline Documentation

This file embeds the English component guide, API, FAQ, and version documentation generated for ${config.brand}. Treat it as the bundled documentation source for projects that install only the npm \`${config.packageName}\` package.

${sections || '## Docs\n\nNo component docs found.'}
`;
};

const renderIndex = ({ config, rows, target }) => `# ${config.brand} Component Reference

<!-- generated by scripts/generate-skill-component-references.mjs; do not edit -->
<!-- source: apps/site-common/docs/component-docs -> content/${target}/components -->
<!-- component-count: ${rows.length} -->

Use this reference to select ${config.brand} components and locate their exact bundled documentation. Do not infer an API from a component name. Open every matching component detail file before writing code.

## Lookup Rules

- Component detail files live at \`references/components/<nav>.md\` inside this skill.
- Read the guide and API sections before using props, events, snippets, children, slots, callbacks, or exposed methods.
- Read FAQ and version sections when behavior differs from expectations or the target project pins an older release.
- Treat the detail file as the offline documentation source; do not ask an ordinary user project for the Any TDF monorepo.

## Component Index

| Category | Component | Route nav | Offline skill docs |
| --- | --- | --- | --- |
${rows.map((row) => `| ${row.category} | ${row.component} | \`${row.nav}\` | \`references/components/${row.nav}.md\` |`).join('\n')}
`;

const listMarkdownNames = (directory) => {
	if (!existsSync(directory)) {
		return [];
	}
	return readdirSync(directory)
		.filter((fileName) => fileName.endsWith('.md'))
		.sort();
};

const compareOutputs = ({ actualIndex, actualDetails, expectedIndex, expectedDetails }) => {
	const changed = [];
	if (!existsSync(actualIndex) || readFileSync(actualIndex, 'utf-8') !== readFileSync(expectedIndex, 'utf-8')) {
		changed.push(path.basename(actualIndex));
	}

	const actualNames = listMarkdownNames(actualDetails);
	const expectedNames = listMarkdownNames(expectedDetails);
	if (actualNames.join('\n') !== expectedNames.join('\n')) {
		changed.push('components/ file list');
	}

	expectedNames.forEach((fileName) => {
		const actualPath = path.join(actualDetails, fileName);
		const expectedPath = path.join(expectedDetails, fileName);
		if (!existsSync(actualPath) || readFileSync(actualPath, 'utf-8') !== readFileSync(expectedPath, 'utf-8')) {
			changed.push(`components/${fileName}`);
		}
	});

	return changed;
};

const writeGeneratedOutputs = ({ actualIndex, actualDetails, expectedIndex, expectedDetails }) => {
	rmSync(actualDetails, { recursive: true, force: true });
	mkdirSync(actualDetails, { recursive: true });
	copyFileSync(expectedIndex, actualIndex);
	listMarkdownNames(expectedDetails).forEach((fileName) => {
		copyFileSync(path.join(expectedDetails, fileName), path.join(actualDetails, fileName));
	});
};

const generateTarget = ({ check, target }) => {
	const config = configs[target];
	const siteCommonRoot = path.join(repositoryRoot, 'apps/site-common');
	const docsArgs = ['run', 'scripts/generate-component-docs.mjs', '--target', target];
	if (check) {
		docsArgs.push('--check');
	}
	execFileSync('bun', docsArgs, { cwd: siteCommonRoot, stdio: 'inherit' });

	const rows = readMenuList().flatMap((group) =>
		group.childs.map((child) => ({
			category: group.class_en,
			component: child.title_en,
			nav: child.nav,
			docs: listDocs(target, child.nav)
		}))
	);

	const packageRoot = path.join(repositoryRoot, 'packages/skills', config.skillPackage);
	const referencesRoot = path.join(packageRoot, target, 'references');
	const actualIndex = path.join(referencesRoot, 'components.md');
	const actualDetails = path.join(referencesRoot, 'components');
	const temporaryRoot = mkdtempSync(path.join(os.tmpdir(), `${target}-skill-components-`));
	const expectedIndex = path.join(temporaryRoot, 'components.md');
	const expectedDetails = path.join(temporaryRoot, 'components');

	try {
		mkdirSync(expectedDetails, { recursive: true });
		writeFileSync(expectedIndex, renderIndex({ config, rows, target }), 'utf-8');
		rows.forEach((row) => {
			writeFileSync(path.join(expectedDetails, `${row.nav}.md`), renderComponentDetail({ config, row }), 'utf-8');
		});

		const formatterPath = path.join(repositoryRoot, 'node_modules/.bin', process.platform === 'win32' ? 'vp.cmd' : 'vp');
		const generatedFiles = [
			expectedIndex,
			...listMarkdownNames(expectedDetails).map((fileName) => path.join(expectedDetails, fileName))
		];
		execFileSync(formatterPath, ['fmt', ...generatedFiles], { cwd: repositoryRoot, stdio: 'inherit' });

		if (check) {
			const changed = compareOutputs({ actualIndex, actualDetails, expectedIndex, expectedDetails });
			if (changed.length > 0) {
				throw new Error(`${config.brand} skill component references are out of date:\n${changed.map((item) => `  - ${item}`).join('\n')}`);
			}
			console.log(`${config.brand} skill component references are up to date (${rows.length} components).`);
			return;
		}

		writeGeneratedOutputs({ actualIndex, actualDetails, expectedIndex, expectedDetails });
		console.log(`Generated ${rows.length} ${config.brand} skill component references.`);
	} finally {
		rmSync(temporaryRoot, { recursive: true, force: true });
	}
};

const options = parseArgs();
const targets = options.target === 'all' ? Object.keys(configs) : [options.target];
targets.forEach((target) => generateTarget({ check: options.check, target }));
