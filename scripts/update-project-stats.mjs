const createChart = (history) => {
	const recentHistory = history.slice(-90);
	const chart = { left: 76, right: 1124, top: 376, bottom: 526 };
	const values = recentHistory.map(({ stars }) => stars);
	const valueMinimum = Math.min(...values);
	const valueMaximum = Math.max(...values);
	const valuePadding = Math.max(1, Math.ceil((valueMaximum - valueMinimum || valueMaximum * 0.02) / 2));
	const minimum = Math.max(0, valueMinimum - valuePadding);
	const maximum = valueMaximum + valuePadding;
	const range = maximum - minimum;
	const points = recentHistory.map((entry, index) => {
		const progress = recentHistory.length === 1 ? 1 : index / (recentHistory.length - 1);
		return {
			...entry,
			x: chart.left + progress * (chart.right - chart.left),
			y: chart.bottom - ((entry.stars - minimum) / range) * (chart.bottom - chart.top)
		};
	});
	const linePath = points.length > 1 ? points.map(({ x, y }, index) => `${index === 0 ? 'M' : 'L'} ${x.toFixed(2)} ${y.toFixed(2)}`).join(' ') : '';
	const areaPath = linePath
		? `${linePath} L ${points.at(-1).x.toFixed(2)} ${chart.bottom} L ${points[0].x.toFixed(2)} ${chart.bottom} Z`
		: '';

	return { recentHistory, chart, minimum, maximum, points, linePath, areaPath };
};

export const renderProjectStatsSvg = (stats, mode, locale = 'en') => {
	validateProjectStats(stats);
	const palette = svgPalettes[mode];
	if (!palette) throw new Error(`Unknown project statistics SVG mode: ${mode}.`);
	const translation = svgTranslations[locale];
	if (!translation) throw new Error(`Unknown project statistics SVG locale: ${locale}.`);
	const { chart, minimum, maximum, points, linePath, areaPath, recentHistory } = createChart(stats.history);
	const firstPoint = points[0];
	const lastPoint = points.at(-1);
	const cards = [
		{ label: translation.stars, value: stats.current.github.stars, note: translation.starsNote },
		{ label: translation.forks, value: stats.current.github.forks, note: translation.forksNote },
		{ label: translation.core, value: stats.current.npm.coreWeeklyDownloads, note: 'STDF · RTDF · VTDF' },
		{
			label: translation.ecosystem,
			value: stats.current.npm.ecosystemWeeklyDownloads,
			note: translation.packageCount(formatNumber(stats.current.npm.packages.length, locale))
		}
	];
	const cardMarkup = cards
		.map(({ label, value, note }, index) => {
			const x = 48 + index * 288;
			return `<g transform="translate(${x} 154)">
		<rect width="264" height="126" rx="12" fill="${palette.surface}" stroke="${palette.divider}" />
		<text x="20" y="30" fill="${palette.mutedText}" font-size="12" font-weight="700" letter-spacing="1.2">${escapeXml(label)}</text>
		<text x="20" y="78" fill="${palette.text}" font-size="34" font-weight="750">${formatNumber(value, locale)}</text>
		<text x="20" y="104" fill="${palette.softText}" font-size="13">${escapeXml(note)}</text>
	</g>`;
		})
		.join('\n\t');
	const gridMarkup = [0, 0.5, 1]
		.map((progress) => {
			const y = chart.top + progress * (chart.bottom - chart.top);
			return `<line x1="${chart.left}" y1="${y}" x2="${chart.right}" y2="${y}" stroke="${palette.divider}" stroke-dasharray="4 8" />`;
		})
		.join('\n\t\t');
	const chartMarkup =
		points.length > 1
			? `<path d="${areaPath}" fill="url(#stats-area)" />
		<path d="${linePath}" fill="none" stroke="${palette.accent}" stroke-width="4" stroke-linecap="round" stroke-linejoin="round" />
		<circle cx="${lastPoint.x}" cy="${lastPoint.y}" r="7" fill="${palette.surface}" stroke="${palette.accent}" stroke-width="4" />`
			: `<circle cx="${lastPoint.x}" cy="${lastPoint.y}" r="8" fill="${palette.surface}" stroke="${palette.accent}" stroke-width="4" />
		<text x="600" y="452" text-anchor="middle" fill="${palette.softText}" font-size="15">${escapeXml(translation.firstDay)}</text>`;
	const trendScope =
		stats.history.length > 90
			? translation.lastNinetyDays
			: `${translation.trackingSince} ${formatDate(stats.history[0].date, locale)}`;
	const description = translation.description({
		stars: formatNumber(stats.current.github.stars, locale),
		forks: formatNumber(stats.current.github.forks, locale),
		downloads: formatNumber(stats.current.npm.ecosystemWeeklyDownloads, locale),
		packages: formatNumber(stats.current.npm.packages.length, locale)
	});

	return `${generatedComment}
<svg xmlns="http://www.w3.org/2000/svg" width="1200" height="600" viewBox="0 0 1200 600" role="img" aria-labelledby="stats-title stats-description" lang="${translation.intlLocale}" xml:lang="${translation.intlLocale}" font-family="Inter, -apple-system, BlinkMacSystemFont, 'Segoe UI', 'Noto Sans', sans-serif">
	<title id="stats-title">${escapeXml(translation.title)}</title>
	<desc id="stats-description">${escapeXml(description)}</desc>
	<defs>
		<linearGradient id="stats-area" x1="0" y1="0" x2="0" y2="1">
			<stop offset="0" stop-color="${palette.accent}" stop-opacity="0.28" />
			<stop offset="1" stop-color="${palette.accent}" stop-opacity="0" />
		</linearGradient>
	</defs>
	<rect width="1200" height="600" rx="18" fill="${palette.background}" />
	<rect x="24" y="24" width="1152" height="552" rx="16" fill="none" stroke="${palette.divider}" />
	<rect x="48" y="48" width="10" height="64" rx="5" fill="${palette.accent}" />
	<text x="78" y="73" fill="${palette.mutedText}" font-size="12" font-weight="700" letter-spacing="1.6">${escapeXml(translation.pulse)}</text>
	<text x="78" y="108" fill="${palette.text}" font-size="31" font-weight="750">${escapeXml(translation.headline)}</text>
	<text x="1152" y="73" text-anchor="end" fill="${palette.secondary}" font-size="12" font-weight="700" letter-spacing="1.2">${escapeXml(translation.snapshot)}</text>
	<text x="1152" y="105" text-anchor="end" fill="${palette.softText}" font-size="13">GitHub + npm · ${escapeXml(formatDate(stats.updatedAt.slice(0, 10), locale))} UTC</text>
	${cardMarkup}
	<text x="48" y="329" fill="${palette.mutedText}" font-size="12" font-weight="700" letter-spacing="1.3">${escapeXml(translation.trend)}</text>
	<text x="1152" y="329" text-anchor="end" fill="${palette.softText}" font-size="12" font-weight="700" letter-spacing="1.1">${escapeXml(trendScope)}</text>
	<rect x="48" y="348" width="1104" height="202" rx="12" fill="${palette.surface}" stroke="${palette.divider}" />
	<g>
		${gridMarkup}
		<text x="64" y="${chart.top + 4}" text-anchor="end" fill="${palette.mutedText}" font-size="11">${formatNumber(maximum, locale)}</text>
		<text x="64" y="${chart.bottom + 4}" text-anchor="end" fill="${palette.mutedText}" font-size="11">${formatNumber(minimum, locale)}</text>
		${chartMarkup}
		<text x="${chart.left}" y="544" fill="${palette.mutedText}" font-size="11">${escapeXml(formatDate(firstPoint.date, locale))}</text>
		<text x="${chart.right}" y="544" text-anchor="end" fill="${palette.mutedText}" font-size="11">${escapeXml(formatDate(lastPoint.date, locale))}</text>
	</g>
	<text x="48" y="570" fill="${palette.mutedText}" font-size="11">${escapeXml(translation.footer(formatNumber(recentHistory.length, locale)))}</text>
</svg>
`;
};

const readExistingStats = async () => {
	const file = Bun.file(dataPath);
	return (await file.exists()) ? file.json() : null;
};

const writeProjectStats = async (stats) => {
	validateProjectStats(stats);
	const svgOutputs = projectStatsLocales.flatMap((locale) =>
		svgModes.map((mode) => [getSvgPath(locale, mode), renderProjectStatsSvg(stats, mode, locale)])
	);
	for (const path of [dataPath, ...svgOutputs.map(([path]) => path)]) mkdirSync(dirname(path), { recursive: true });
	await Promise.all([
		Bun.write(dataPath, `${JSON.stringify(stats, null, 2)}\n`),
		...svgOutputs.map(([path, output]) => Bun.write(path, output))
	]);
};

const checkGeneratedStats = async () => {
	const stats = validateProjectStats(await Bun.file(dataPath).json());
	const outputs = projectStatsLocales.flatMap((locale) =>
		svgModes.map((mode) => [getSvgPath(locale, mode), renderProjectStatsSvg(stats, mode, locale)])
	);
	const stalePaths = [];
	for (const [path, expected] of outputs) {
		const file = Bun.file(path);
		const actual = (await file.exists()) ? await file.text() : '';
		if (actual !== expected) stalePaths.push(path.replace(`${repositoryRoot}/`, ''));
	}
	if (stalePaths.length > 0) throw new Error(`Generated project statistics are stale: ${stalePaths.join(', ')}`);
	console.log(
		`PASS project statistics (${stats.history.length} daily snapshots, ${stats.current.npm.packages.length} npm packages, ${projectStatsLocales.length} locales)`
	);
};

const run = async () => {
	if (process.argv.includes('--check')) {
		await checkGeneratedStats();
		return;
	}
	if (process.argv.includes('--render')) {
		await writeProjectStats(await Bun.file(dataPath).json());
		console.log(`Rendered project statistics SVG assets in ${projectStatsLocales.length} locales from the committed snapshot.`);
		return;
	}

	const previous = await readExistingStats();
	const current = await collectCurrentStats();
	const stats = createProjectStatsDocument({ current, updatedAt: new Date().toISOString(), previous });
	await writeProjectStats(stats);
	console.log(
		`Updated project statistics: ${stats.current.github.stars} stars and ${stats.current.npm.ecosystemWeeklyDownloads} weekly npm downloads.`
	);
};

if (import.meta.main) await run();
