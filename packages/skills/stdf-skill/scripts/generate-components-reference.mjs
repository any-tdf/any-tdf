import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const packageRoot = path.resolve(scriptDir, '..');
const stdfRoot = path.resolve(packageRoot, '../..');
const anyRoot = path.resolve(stdfRoot, '..');

const generateComponentDocs = () => {
	const commonRoot = path.join(anyRoot, 'apps/site-common');
	const generator = path.join(commonRoot, 'scripts/generate-component-docs.mjs');
	if (!existsSync(generator)) {
		console.warn('Skipped component docs generation because site-common is unavailable.');
		return;
	}

	execFileSync('bun', ['run', 'scripts/generate-component-docs.mjs', '--target', 'stdf'], {
		cwd: commonRoot,
		stdio: 'inherit'
	});
};

const parseMenuList = () => {
	const sourcePath = path.join(anyRoot, 'apps/site-common/src/stdf-data/menuList.ts');
	const source = readFileSync(sourcePath, 'utf-8');
	const marker = 'export const menuList: MenuList[] = ';
	const start = source.indexOf(marker);
	const arrayStart = source.indexOf('[', start);
	const arrayEnd = source.indexOf('\n];', arrayStart) + 2;
	const arrayText = source.slice(arrayStart, arrayEnd);
	return new Function(`return ${arrayText};`)();
};

const listDocs = (componentName) => {
	const docsDir = path.join(anyRoot, 'content/stdf/components', componentName);
	if (!existsSync(docsDir)) {
		return [];
	}
	const preferred = ['guide_en.md', 'api_en.md', 'FAQ_en.md', 'version_en.md'];
	return preferred.filter((item) => existsSync(path.join(docsDir, item))).map((item) => `content/stdf/components/${componentName}/${item}`);
};

const normalizeEnglishDoc = (content) =>
	content.replace(
		'[德育处主任](https://gitee.com/k21vin/front-end-data-visualization/tree/master/src/views/Native/PureCSS/pages/Loading/components)',
		'[front-end-data-visualization](https://gitee.com/k21vin/front-end-data-visualization/tree/master/src/views/Native/PureCSS/pages/Loading/components)'
	);

const readDoc = (docPath) => normalizeEnglishDoc(readFileSync(path.join(anyRoot, docPath), 'utf-8').trim());

const formatDocTitle = (docPath) => docPath.split('/').pop().replace('_en.md', '').replace('.md', '');

const renderComponentDetail = (row) => {
	const docSections = row.docs
		.map((docPath) => {
			const title = formatDocTitle(docPath);
			return `## ${title}\n\n${readDoc(docPath)}`;
		})
		.join('\n\n');

	return `# ${row.component}

<!-- generated by packages/skills/stdf-skill/scripts/generate-components-reference.mjs -->

- Category: ${row.category}
- Route nav: \`${row.nav}\`

## Offline Documentation

This file embeds the English component guide, API, FAQ, and version documentation. Treat the content below as the bundled documentation source for ordinary STDF projects that only install the npm \`stdf\` package.

${docSections || '## Docs\n\nNo component docs found.'}
`;
};

generateComponentDocs();

const menuList = parseMenuList();
const rows = menuList.flatMap((group) =>
	group.childs.map((child) => ({
		category: group.class_en,
		component: child.title_en,
		nav: child.nav,
		docs: listDocs(child.nav)
	}))
);

const componentReferenceDir = path.join(packageRoot, 'skill/references/components');
rmSync(componentReferenceDir, { recursive: true, force: true });
mkdirSync(componentReferenceDir, { recursive: true });

rows.forEach((row) => {
	writeFileSync(path.join(componentReferenceDir, `${row.nav}.md`), renderComponentDetail(row), 'utf-8');
});

const output = `# STDF Component Reference

<!-- generated by packages/skills/stdf-skill/scripts/generate-components-reference.mjs -->
<!-- component-count: ${rows.length} -->

Use this reference when an AI task needs to select STDF components, locate documentation, or inspect implementation details. Do not guess component APIs from the component name. Open the generated component detail file first. The detail files are bundled in this Skill package for ordinary user projects that only install the npm \`stdf\` package and do not have STDF repository docs locally.

## Lookup Rules

- Generated component detail files live under \`references/components/<nav>.md\` inside this Skill package.
- Use the generated detail files as the offline component documentation source.
- Do not ask ordinary user projects to provide STDF repository docs or component source files.
- When a generated component detail file is loaded, trust the embedded guide, API, FAQ, and version sections for that component.

## Component Index

| Category | Component | Route nav | Offline Skill docs |
| --- | --- | --- | --- |
${rows.map((row) => `| ${row.category} | ${row.component} | \`${row.nav}\` | \`references/components/${row.nav}.md\` |`).join('\n')}
`;

const referencePath = path.join(packageRoot, 'skill/references/components.md');
const formatterPath = path.join(packageRoot, 'node_modules/.bin', process.platform === 'win32' ? 'vp.cmd' : 'vp');
const detailPaths = rows.map((row) => path.join(componentReferenceDir, `${row.nav}.md`));

writeFileSync(referencePath, output, 'utf-8');
execFileSync(formatterPath, ['fmt', referencePath, ...detailPaths], {
	cwd: packageRoot,
	stdio: 'inherit'
});
console.log(`Generated ${rows.length} component entries and detail files.`);
